// Writes foundry/chrab-sync/scripts/runtime/behaviorRuntime.mjs: the site's
// behavior runtime (src/lib/foundryBehaviors.js BEHAVIOR_RUNTIME), which Chrab
// Sync runs itself for items built with the module runtime (Phase 4). One
// source: today's macros and the module run the same code.
//
//   npm run module-runtime
//
// test/runtime.test.mjs fails when the file is out of date. Not shipped (the
// module zip takes scripts/ and styles/ only).
import { writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '../../..')
const { BEHAVIOR_RUNTIME, BEHAVIOR_RUNTIME_VERSION } = await import(pathToFileURL(path.join(root, 'src/lib/foundryBehaviors.js')).href)

export function runtimeFile() {
  return `// GENERATED by foundry/chrab-sync/tools/build-runtime.mjs from the Compendium's
// src/lib/foundryBehaviors.js (BEHAVIOR_RUNTIME). Don't edit: change it there
// and run "npm run module-runtime".
export const BEHAVIOR_RUNTIME_VERSION = ${JSON.stringify(BEHAVIOR_RUNTIME_VERSION)}
export const BEHAVIOR_RUNTIME = ${JSON.stringify(BEHAVIOR_RUNTIME)}
`
}

export const runtimePath = path.join(root, 'foundry/chrab-sync/scripts/runtime/behaviorRuntime.mjs')

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(path.dirname(runtimePath), { recursive: true })
  writeFileSync(runtimePath, runtimeFile())
  console.log(`Wrote ${path.relative(root, runtimePath)} (${BEHAVIOR_RUNTIME.length} characters, version ${BEHAVIOR_RUNTIME_VERSION}).`)
}
